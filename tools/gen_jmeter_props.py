"""slo.json -> a JMeter property file, for one profile.

This is the bridge that keeps JMeter honest. k6 reads slo.json directly; JMeter
cannot, so its numbers are generated here instead of being typed into the .jmx.
The generated file is a build artifact, not source, and is gitignored -- if it
ever drifts from slo.json it is because someone edited the wrong thing, and
regenerating fixes it.

Both workload models come out of the same .jmx. The trick is that JMeter's
Constant Throughput Timer only ever *delays* a thread, so setting its target
absurdly high makes it a no-op:

  closed profile -> think time 300ms, throughput target effectively infinite
                    (the timer never fires; pacing comes from think time)
  open profile   -> think time 0, throughput target = rate_per_s * 60
                    (the timer paces arrivals; concurrency is capped by threads)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import slo as slo_mod  # noqa: E402

# Large enough that the timer never delays anything, small enough to stay well
# inside a double. Chosen rather than a sentinel so the .jmx needs no branching.
UNCAPPED_PER_MIN = 6_000_000.0


def main(out_path, profile_name=None, load_multiplier=1.0):
    cfg = slo_mod.load()
    name, prof = slo_mod.profile(cfg, profile_name)
    host, _, port = cfg["base_url"].split("//", 1)[1].partition(":")

    if prof["model"] == "closed":
        threads = max(1, round(prof["vus"] * load_multiplier))
        rate_per_min = UNCAPPED_PER_MIN
    else:
        threads = max(1, round(prof["max_vus"] * load_multiplier))
        rate_per_min = prof["rate_per_s"] * load_multiplier * 60.0

    lines = [
        f"# GENERATED by tools/gen_jmeter_props.py from slo.json "
        f"(profile={name}, load_multiplier={load_multiplier}). Do not edit.",
        f"sut.host={host}",
        f"sut.port={port or '80'}",
        f"wl.vus={threads}",
        f"wl.ramp_s={prof['ramp_up_s']}",
        # JMeter's scheduler duration is total wall clock including the ramp,
        # while k6's stages list them separately. Same steady window either way.
        f"wl.total_s={prof['ramp_up_s'] + prof['duration_s']}",
        f"wl.think_ms={prof['think_time_ms']}",
        f"wl.rate_per_min={rate_per_min}",
    ]
    for s in slo_mod.scenarios(cfg):
        lines.append(f"sc.{s['name']}.weight={float(s['weight'])}")
        lines.append(f"sc.{s['name']}.path={s['path']}")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}  profile={name} model={prof['model']} "
          f"threads={threads} think={prof['think_time_ms']}ms "
          f"rate={rate_per_min:.0f}/min")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "reports/jmeter.props",
         sys.argv[2] if len(sys.argv) > 2 else None,
         float(sys.argv[3]) if len(sys.argv) > 3 else 1.0)
